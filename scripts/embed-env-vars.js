#!/usr/bin/env node

/**
 * 🚀 Embed Environment Variables Script
 * 
 * This script generates a TypeScript file with embedded environment variables
 * that will be bundled with the packaged app. This allows the packaged .exe
 * to access environment variables like GITHUB_TOKEN for OTA updates.
 * 
 * Works for both:
 * - Local builds: `npm run make` (reads from .env file)
 * - CI builds: GitHub Actions (reads from environment variables/secrets)
 * 
 * IMPORTANT: This must run BEFORE electron-forge builds (before Vite compiles)
 */

const fs = require('fs');
const path = require('path');
const { config: loadDotenv } = require('dotenv');

// Load .env file if it exists (for local development)
loadDotenv();

// List of environment variables to embed
// Only include variables that are safe to embed (not user-specific secrets)
const envVarsToEmbed = [
  'GITHUB_TOKEN',
  'GH_TOKEN',
  'VITE_GITHUB_TOKEN',
  'SUPABASE_URL',
  'SUPABASE_ANON_KEY',
  'AUTH_SUPABASE_URL',
  'AUTH_SUPABASE_ANON_KEY',
  'SUPABASE_SERVICE_ROLE_KEY',
  'SENTRY_DSN',
  'AZURE_API_KEY',
  'AZURE_RESOURCE_NAME',
  'AZURE_DEPLOYMENT_NAME',
  'AZURE_API_VERSION',
  'AZURE_ENDPOINT',
  'E2B_API_KEY',
  'VITE_VERCEL_TOKEN',
  'CLOUDFLARE_R2_ACCOUNT_ID',
  'CLOUDFLARE_R2_ACCESS_KEY_ID',
  'CLOUDFLARE_R2_SECRET_ACCESS_KEY',
  'CLOUDFLARE_R2_BUCKET_NAME',
  'CLOUDFLARE_R2_REGION',
  'GA4_MEASUREMENT_ID',
];

// Generate the embedded config file
const configDir = path.join(__dirname, '..', 'src', 'config');
const configFile = path.join(configDir, 'embedded-env.ts');

// Ensure config directory exists
if (!fs.existsSync(configDir)) {
  fs.mkdirSync(configDir, { recursive: true });
}

// Build the TypeScript file content
let content = `/**
 * ⚠️ AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * 
 * This file is generated by scripts/embed-env-vars.js
 * It contains environment variables embedded at build time.
 * 
 * Generated: ${new Date().toISOString()}
 * Build Environment: ${process.env.CI ? 'CI' : 'Local'}
 */

export const embeddedEnv: Record<string, string | undefined> = {
`;

// Add each environment variable
let embeddedCount = 0;
envVarsToEmbed.forEach((varName) => {
  let value = process.env[varName];
  
  // Special handling for GITHUB_TOKEN: prefer APPLAA_GITHUB_TOKEN for embedding
  // (don't use the automatic GITHUB_TOKEN from GitHub Actions - that's for publishing)
  if (varName === 'GITHUB_TOKEN') {
    value = process.env.APPLAA_GITHUB_TOKEN || process.env.GITHUB_TOKEN || process.env.GH_TOKEN || process.env.VITE_GITHUB_TOKEN;
  }
  
  if (value !== undefined && value !== '') {
    // Escape backslashes, quotes, and newlines for TypeScript string
    const escapedValue = value
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\n/g, '\\n')
      .replace(/\r/g, '\\r');
    content += `  ${varName}: "${escapedValue}",\n`;
    embeddedCount++;
  } else {
    content += `  ${varName}: undefined,\n`;
  }
});

content += `};

/**
 * Get an embedded environment variable
 */
export function getEmbeddedEnv(varName: string): string | undefined {
  return embeddedEnv[varName];
}

/**
 * Get GitHub token (checks multiple possible variable names)
 * Priority: GITHUB_TOKEN > GH_TOKEN > VITE_GITHUB_TOKEN
 */
export function getGitHubToken(): string | undefined {
  return embeddedEnv.GITHUB_TOKEN || embeddedEnv.GH_TOKEN || embeddedEnv.VITE_GITHUB_TOKEN;
}
`;

// Write the file
fs.writeFileSync(configFile, content, 'utf8');

console.log('✅ Embedded environment variables file generated:');
console.log(`   ${path.relative(process.cwd(), configFile)}`);
console.log(`   Variables embedded: ${embeddedCount}/${envVarsToEmbed.length}`);
if (embeddedCount > 0) {
  const hasToken = !!(process.env.APPLAA_GITHUB_TOKEN || process.env.GITHUB_TOKEN || process.env.GH_TOKEN || process.env.VITE_GITHUB_TOKEN);
  console.log(`   ✓ GitHub token: ${hasToken ? 'Found' : 'Not found'}`);
} else {
  console.log(`   ⚠️  No environment variables embedded - check your .env file or CI secrets`);
}
